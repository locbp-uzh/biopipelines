"""Vina rejects a receptor PDBQT that carries any record it does not parse.

Open Babel 3.2 copies the input's COMPND and AUTHOR records into the PDBQT it writes, and Vina's rigid-receptor
parser accepts only ATOM, HETATM, REMARK, TER, END and WARNING lines, so every receptor protonated by `obabel`
(which writes both records) failed with "Unknown or inappropriate tag found in rigid receptor" and the pair became
a `failure` row. The converted receptor now keeps only the records Vina parses.
"""

import importlib.util
import pathlib

import pytest

pytest.importorskip("rdkit")

ATOM = "ATOM      1  N   ALA A  13      22.637   5.768  11.762  0.00  0.00    +0.000 NA"
OBABEL_32_RECEPTOR = "\n".join([
    "REMARK  Name = /path/to/p1_h.pdb",
    "COMPND    /path/to/p1_clean.pdb ",
    "AUTHOR    GENERATED BY OPEN BABEL 3.2.1",
    "REMARK                            x       y       z     vdW  Elec       q    Type",
    ATOM,
    "TER ",
]) + "\n"


@pytest.fixture(scope="module")
def vina_backend():
    """Load the pipe script directly; pipe_scripts is not an importable package."""
    path = pathlib.Path(__file__).resolve().parent.parent / "pipe_scripts" / "pipe_vina_backend.py"
    spec = importlib.util.spec_from_file_location("pipe_vina_backend", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_receptor_pdbqt_keeps_only_the_records_vina_parses(vina_backend, monkeypatch, tmp_path):
    def fake_convert(src, dst, extra_args=None):
        pathlib.Path(dst).write_text(OBABEL_32_RECEPTOR)
        return dst

    monkeypatch.setattr(vina_backend, "convert", fake_convert)
    dst = tmp_path / "p1_receptor.pdbqt"
    assert vina_backend.receptor_pdbqt("p1_h.pdb", str(dst)) == str(dst)
    lines = dst.read_text().splitlines()
    assert ATOM in lines
    assert [line for line in lines if line.startswith(("COMPND", "AUTHOR"))] == []
    allowed = ("ATOM  ", "HETATM", "REMARK", "TER", "END", "WARNING")
    assert all(line.startswith(allowed) for line in lines if line)
